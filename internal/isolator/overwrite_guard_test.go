// overwrite_guard_test.go 守卫票 35（audit-fixes B5 / C-07 / P1-34）：
//
//   - Setup 不得覆盖用户已有的 flake.nix / devcontainer.json（除 --force）；
//   - Teardown 只删自己写过的文件（内容 hash 存 persistedState），用户改写过
//     的、以及旧存量无从证明归属的一律跳过并记日志；
//   - flake.lock 是 `nix develop` 的产物，按例外无条件删除；
//   - container 侧 Teardown 不删 devcontainer.json（复核确认，见
//     TestContainerTeardownHasNoFileDeletion）。
//
// 这些用例不触碰 docker/nix：Setup 的文件写入段与 Teardown 的删除段都是纯
// 本地文件操作（container 的 docker run 段不在覆盖范围内，用直接调用
// generateDevcontainer 的方式覆盖，它就是 Setup 中早于 docker run 的第一步）。
package isolator

import (
	"context"
	"log"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const userFlakeContent = "{ description = \"hand-written by the user\"; }\n"

// captureLog 把标准库 log 的输出重定向到缓冲区，用于断言 C-07 的降级/跳过
// 日志（仓库既有约定：log.SetOutput + t.Cleanup 还原）。
func captureLog(t *testing.T) *strings.Builder {
	t.Helper()
	var buf strings.Builder
	old := log.Writer()
	log.SetOutput(&buf)
	t.Cleanup(func() { log.SetOutput(old) })
	return &buf
}

func writeFileT(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFileT(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(data)
}

func mustNotExist(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Stat(path); err == nil {
		t.Errorf("%s must have been removed", path)
	}
}

func mustExist(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Stat(path); err != nil {
		t.Errorf("%s must still exist: %v", path, err)
	}
}

// TestNixSetupRefusesToOverwriteUserFlake（C-07 / 守卫 35-2）：目标 flake.nix
// 已存在（用户手写）时 Setup 必须报错拒绝——既不覆盖内容，也不落 state，
// 否则随后的 teardown 会把它当 xdev 产物删掉。
func TestNixSetupRefusesToOverwriteUserFlake(t *testing.T) {
	home, proj := t.TempDir(), t.TempDir()
	flake := filepath.Join(proj, "flake.nix")
	writeFileT(t, flake, userFlakeContent)

	n := &nixIsolator{xmdeDir: home}
	err := n.Setup(context.Background(), &EnvironmentSpec{WorkingDir: proj})
	if err == nil {
		t.Fatal("Setup must refuse to overwrite an existing user flake.nix")
	}
	if !strings.Contains(err.Error(), "flake.nix") || !strings.Contains(err.Error(), "--force") {
		t.Errorf("error must name the file and the escape hatch: %v", err)
	}
	if got := readFileT(t, flake); got != userFlakeContent {
		t.Errorf("user flake.nix was overwritten: %q", got)
	}
	if _, err := os.Stat(statePath(home, string(ModeNix))); err == nil {
		t.Error("a refused Setup must not persist state — teardown would then delete the user's flake.nix")
	}
}

// TestNixSetupForceOverwritesUserFlake：--force 显式放行覆盖，并把写入内容
// 的 hash 记进 persistedState（跨进程 teardown 的唯一凭据）。
func TestNixSetupForceOverwritesUserFlake(t *testing.T) {
	home, proj := t.TempDir(), t.TempDir()
	flake := filepath.Join(proj, "flake.nix")
	writeFileT(t, flake, userFlakeContent)

	n := &nixIsolator{xmdeDir: home}
	if err := n.Setup(context.Background(), &EnvironmentSpec{WorkingDir: proj, Force: true}); err != nil {
		t.Fatalf("Setup with Force: %v", err)
	}
	got := readFileT(t, flake)
	if !strings.Contains(got, "xdev isolated environment") {
		t.Errorf("flake.nix was not regenerated by xdev: %q", got)
	}
	st := loadState(home, string(ModeNix))
	if len(st.WrittenFiles) == 0 {
		t.Fatal("Setup must record the SHA-256 of what it wrote (C-07)")
	}
	if want, have := contentSHA256([]byte(got)), st.WrittenFiles[stateKey(flake)]; want != have {
		t.Errorf("recorded hash = %q, want %q", have, want)
	}
}

// TestContainerSetupRefusesExistingDevcontainer（C-07 / 守卫 35-2）：
// container 侧同样先做存在性门（generateDevcontainer 是 Setup 里早于
// docker run 的写入段），--force 才放行。
func TestContainerSetupRefusesExistingDevcontainer(t *testing.T) {
	const userDC = "{\n  \"name\": \"user-devcontainer\"\n}\n"
	home, proj := t.TempDir(), t.TempDir()
	dc := filepath.Join(proj, ".devcontainer", "devcontainer.json")
	writeFileT(t, dc, userDC)

	c := &containerIsolator{xmdeDir: home, projectDir: proj, spec: &EnvironmentSpec{Env: map[string]string{}}}
	err := c.generateDevcontainer()
	if err == nil {
		t.Fatal("generateDevcontainer must refuse to overwrite an existing devcontainer.json")
	}
	if !strings.Contains(err.Error(), "devcontainer.json") || !strings.Contains(err.Error(), "--force") {
		t.Errorf("error must name the file and the escape hatch: %v", err)
	}
	if got := readFileT(t, dc); got != userDC {
		t.Errorf("user devcontainer.json was overwritten: %q", got)
	}

	c2 := &containerIsolator{xmdeDir: home, projectDir: proj, spec: &EnvironmentSpec{Env: map[string]string{}, Force: true}}
	if err := c2.generateDevcontainer(); err != nil {
		t.Fatalf("generateDevcontainer with Force: %v", err)
	}
	got := readFileT(t, dc)
	if !strings.Contains(got, "xdev-isolated") {
		t.Errorf("devcontainer.json was not regenerated by xdev: %q", got)
	}
	if c2.writtenFiles[stateKey(dc)] != contentSHA256([]byte(got)) {
		t.Errorf("container Setup must record the hash of the file it wrote, got %v", c2.writtenFiles)
	}
}

// TestNixTeardownRemovesOnlyFilesItWrote：正常路径——自己写的 flake.nix 与
// nix develop 产物 flake.lock 被清理，用户自有文件不受影响；teardown 走
// 「新进程只从 state 恢复」的路径，覆盖跨进程语义。
func TestNixTeardownRemovesOnlyFilesItWrote(t *testing.T) {
	home, proj := t.TempDir(), t.TempDir()
	if err := (&nixIsolator{xmdeDir: home}).Setup(context.Background(), &EnvironmentSpec{WorkingDir: proj}); err != nil {
		t.Fatalf("Setup: %v", err)
	}
	flake := filepath.Join(proj, "flake.nix")
	lock := filepath.Join(proj, "flake.lock")
	userOwned := filepath.Join(proj, "shell.nix")
	writeFileT(t, lock, "{}\n")        // nix develop 的产物
	writeFileT(t, userOwned, "user\n") // 用户自己的文件
	mustExist(t, flake)

	// 新进程：只有 <home>/isolate/nix.json 可用。
	n2 := &nixIsolator{xmdeDir: home}
	n2.loadSaved()
	if err := n2.Teardown(context.Background()); err != nil {
		t.Fatalf("Teardown: %v", err)
	}
	mustNotExist(t, flake)
	mustNotExist(t, lock)
	mustExist(t, userOwned)
	mustNotExist(t, statePath(home, string(ModeNix)))
}

// TestNixTeardownLeavesUserModifiedFile：setup 之后用户改写了 flake.nix →
// hash 不匹配 → 不得删除（只记日志）。flake.lock 属例外，仍无条件清理。
func TestNixTeardownLeavesUserModifiedFile(t *testing.T) {
	home, proj := t.TempDir(), t.TempDir()
	if err := (&nixIsolator{xmdeDir: home}).Setup(context.Background(), &EnvironmentSpec{WorkingDir: proj}); err != nil {
		t.Fatalf("Setup: %v", err)
	}
	flake := filepath.Join(proj, "flake.nix")
	lock := filepath.Join(proj, "flake.lock")
	writeFileT(t, lock, "{}\n")
	writeFileT(t, flake, userFlakeContent) // 用户接管了这个文件

	logs := captureLog(t)
	n2 := &nixIsolator{xmdeDir: home}
	n2.loadSaved()
	if err := n2.Teardown(context.Background()); err != nil {
		t.Fatalf("Teardown: %v", err)
	}
	if got := readFileT(t, flake); got != userFlakeContent {
		t.Errorf("Teardown deleted/rewrote a user-modified flake.nix: %q", got)
	}
	if !strings.Contains(logs.String(), flake) {
		t.Errorf("Teardown must log why it skipped %s, got logs: %q", flake, logs.String())
	}
	mustNotExist(t, lock)
}

// TestNixTeardownLegacyStateSkipsRemovalAndLogs（C-07 / 守卫 35-2）：旧存量
// 的 state 文件（C-07 之前写入，没有 writtenFiles 记录）无法证明 flake.nix
// 的归属 → 降级为「不删 + 记日志」。flake.lock 按 nix develop 产物例外，
// 无论 state 新旧都删除。
func TestNixTeardownLegacyStateSkipsRemovalAndLogs(t *testing.T) {
	home, proj := t.TempDir(), t.TempDir()
	flake := filepath.Join(proj, "flake.nix")
	lock := filepath.Join(proj, "flake.lock")
	writeFileT(t, flake, userFlakeContent)
	writeFileT(t, lock, "{}\n")
	// 旧格式：只有 flakeDir/projectDir，没有 writtenFiles。
	saveState(home, string(ModeNix), persistedState{FlakeDir: proj, ProjectDir: proj})

	logs := captureLog(t)
	n := &nixIsolator{xmdeDir: home}
	n.loadSaved()
	if err := n.Teardown(context.Background()); err != nil {
		t.Fatalf("Teardown: %v", err)
	}
	if got := readFileT(t, flake); got != userFlakeContent {
		t.Errorf("legacy teardown must not delete an unproven flake.nix, got %q", got)
	}
	if !strings.Contains(logs.String(), "no recorded content hash") {
		t.Errorf("legacy degradation must be logged, got: %q", logs.String())
	}
	mustNotExist(t, lock)
	mustNotExist(t, statePath(home, string(ModeNix)))
}

// TestContainerTeardownHasNoFileDeletion（C-07 复核确认）：container 侧
// Teardown 只 `docker rm -f` 容器，**不**删除 devcontainer.json（用户可能
// 把它提交进版本库）。此守卫用源码级断言锁住「不得新增文件删除逻辑」——
// 没有 docker 守护进程时无法用行为测试覆盖该分支。
func TestContainerTeardownHasNoFileDeletion(t *testing.T) {
	src, err := os.ReadFile("container.go")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(src), "os.Remove(") {
		t.Error("container.go must not delete files: C-07 confirmed that container teardown only removes the docker container (devcontainer.json is left in place)")
	}
}
